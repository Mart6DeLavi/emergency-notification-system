import http from 'k6/http';
import { check, sleep } from 'k6';

const BASE = __ENV.BASE_URL || 'http://api-gateway:8007';
const RUN_ID = __ENV.TEST_RUN_ID || 'manual';
const HEADERS = {
  'Content-Type': 'application/json',
  'X-Sensa-Test-Mode': 'true',
  'X-Sensa-Test-Run': RUN_ID,
};

export const options = {
  vus: Number(__ENV.VUS || 10),
  duration: __ENV.DURATION || '60s',
  thresholds: {
    http_req_failed: ['rate<0.10'],
  },
};

export function setup() {
  const email = __ENV.TEST_EMAIL || 'ios-test4@sensanotify.com';
  const password = __ENV.TEST_PASSWORD || 'TestPass123!';
  const res = http.post(`${BASE}/api/v1/auth/login`, JSON.stringify({ email, password }), {
    headers: { 'Content-Type': 'application/json' },
  });
  check(res, { 'login 200': (r) => r.status === 200 });
  return { token: res.json('token') };
}

function authHeaders(data) {
  return { ...HEADERS, Authorization: `Bearer ${data.token}` };
}

function readScenario(data) {
  const headers = authHeaders(data);
  const notifications = http.get(`${BASE}/api/v1/notifications`, { headers });
  check(notifications, { 'notifications 200': (r) => r.status === 200 });
  const emergencies = http.get(`${BASE}/api/v1/emergencies/my`, { headers });
  check(emergencies, { 'emergencies 200': (r) => r.status === 200 });
}

function broadcastScenario(data) {
  const payload = JSON.stringify({
    alertType: 'OTHER',
    title: 'SENSA load test alert',
    message: 'Synthetic alert generated by the load test. No delivery is performed.',
    audience: 'ALL',
    radiusKm: null,
  });
  const res = http.post(`${BASE}/api/v1/notifications/broadcast`, payload, {
    headers: authHeaders(data),
  });
  check(res, { 'broadcast 200': (r) => r.status === 200 });
}

export default function (data) {
  const scenario = __ENV.SCENARIO || 'read';
  if (scenario === 'broadcast') {
    broadcastScenario(data);
  } else if (scenario === 'mixed') {
    if (__ITER % 10 < 7) readScenario(data); else broadcastScenario(data);
  } else {
    readScenario(data);
  }
  sleep(0.2);
}
